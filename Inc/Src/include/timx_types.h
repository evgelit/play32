#define PLAY32_TIMx_PERIPHERAL    (1UL<<30) // 0x4000 0000

#define PLAY32_TIMx_SIZE          (0x0400U)

#define PLAY32_TIM2_BASE_POS      (0U)
#define PLAY32_TIM3_BASE_POS      (1U)
#define PLAY32_TIM4_BASE_POS      (2U)
#define PLAY32_TIM5_BASE_POS      (3U)

#define PLAY32_TIM2_BASE          (PLAY32_TIMx_PERIPHERAL_BASE + (PLAY32_TIM2_BASE_POS * PLAY32_TIMx_SIZE)) //0x4000 0000
#define PLAY32_TIM3_BASE          (PLAY32_TIMx_PERIPHERAL_BASE + (PLAY32_TIM3_BASE_POS * PLAY32_TIMx_SIZE)) //0x4000 0400
#define PLAY32_TIM4_BASE          (PLAY32_TIMx_PERIPHERAL_BASE + (PLAY32_TIM4_BASE_POS * PLAY32_TIMx_SIZE)) //0x4000 0800
#define PLAY32_TIM5_BASE          (PLAY32_TIMx_PERIPHERAL_BASE + (PLAY32_TIM5_BASE_POS * PLAY32_TIMx_SIZE)) //0x4000 0C00

typedef struct {
    volatile uint32_t CR1;
    volatile uint32_t CR2;
    volatile uint32_t SMCR;
    volatile uint32_t DIER;
    volatile uint32_t SR;
    volatile uint32_t EGR;
    volatile uint32_t CCMR1;
    volatile uint32_t CCMR2;
    volatile uint32_t CCER;
    volatile uint32_t CNT;
    volatile uint32_t PSC;
    volatile uint32_t ARR;
    uint32_t PLAY32_TIMx_RESERVED_0;
    volatile uint32_t CCR1;
    volatile uint32_t CCR2;
    volatile uint32_t CCR3;
    volatile uint32_t CCR4;
    uint32_t PLAY32_TIMx_RESERVED_1;
    volatile uint32_t DCR;
    volatile uint32_t DMAR;
    volatile uint32_t OR;
} PLAY32_TIMx_TypeDef;

#define PLAY32_TIM2 ((PLAY32_TIMx_TypeDef *)PLAY32_TIM2_BASE)
#define PLAY32_TIM3 ((PLAY32_TIMx_TypeDef *)PLAY32_TIM3_BASE)
#define PLAY32_TIM4 ((PLAY32_TIMx_TypeDef *)PLAY32_TIM4_BASE)
